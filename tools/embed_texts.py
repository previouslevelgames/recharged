#!/usr/bin/env python3
"""Writes Recharged's English texts (assets/lang/en/*.json) as a C++ table.

The program has its English built in (src/bootstrap/texts.cpp): it shows
English, never IDs, without its assets folder or before one is loaded.

Usage: embed_texts.py ENGLISH_FOLDER OUTPUT.cpp
"""

import json
import sys
from pathlib import Path


def flatten(value, prefix, out):
    if isinstance(value, str):
        out[prefix] = value
    elif isinstance(value, dict):
        for name, item in value.items():
            flatten(item, f"{prefix}.{name}", out)
    else:
        raise SystemExit(f"{prefix}: not a text")


def literal(text):
    # Octal escapes for everything outside printable ASCII (UTF-8 bytes as
    # they are), so no escape runs into the next character.
    out = ['"']
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F and char != "?":
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    out.append('"')
    return "".join(out)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    folder, output = Path(sys.argv[1]), Path(sys.argv[2])
    texts = {}
    for path in sorted(folder.glob("*.json")):
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except ValueError as error:
            raise SystemExit(f"{path}: {error}")
        flatten(document, path.stem, texts)
    lines = [
        "// Generated by tools/embed_texts.py from assets/lang/en: do not edit.",
        "#include <cstddef>",
        "namespace mscharged::texts {",
        "struct EnglishText { const char* id; const char* text; };",
        "extern const EnglishText kEnglishTexts[] = {",
    ]
    lines += [f"    {{{literal(id_)}, {literal(text)}}}," for id_, text in sorted(texts.items())]
    lines += ["    {nullptr, nullptr},", "};", f"extern const std::size_t kEnglishTextCount = {len(texts)};", "}"]
    content = "\n".join(lines) + "\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
